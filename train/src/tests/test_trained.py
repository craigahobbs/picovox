import json
import os
import runpy
import shutil
import sys
import tempfile
import unittest
import unittest.mock
import warnings

from picovox_train import ROOT, trained

from .helpers import captured


# A G2P module and a voice module, as generated
G2P_MODULE = '// Generated by context.py export - provenance A\n\nexport const g2pModel = {\'version\': 1};\n'
VOICE_MODULE = '// Generated by package.py\nexport const manifest = {"parameterCount":305035,"provenance":{"commit":"a"}};\n'

# The gate's summary (distill pick --against baseline)
SUMMARY = {
    'against': 'baseline', 'tolerance': {'mos': 0.05, 'wer': 1.0, 'similarity': 0.85},
    'rows': [{'name': 'baseline', 'mos': 4.147, 'wer': 1.06, 'similarity': 1.0},
             {'name': 'student', 'mos': 4.15, 'wer': 1.1, 'similarity': 0.972, 'withinTolerance': True}]
}


class TestTrained(unittest.TestCase):

    def setUp(self):
        self.directory = tempfile.mkdtemp()
        self.train_dir = os.path.join(self.directory, 'train')
        self.models_dir = os.path.join(self.directory, 'models')
        os.makedirs(self.train_dir)
        os.makedirs(self.models_dir)
        patcher = unittest.mock.patch.object(trained, 'MODELS_DIR', self.models_dir)
        patcher.start()
        self.addCleanup(patcher.stop)

    def tearDown(self):
        shutil.rmtree(self.directory)

    def write(self, path, text):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as file:
            file.write(text)

    def read(self, path):
        with open(path, encoding='utf-8') as file:
            return file.read()

    # The committed modules, and the trained ones (each with its stamp), and the gate's summary (default SUMMARY)
    def models(self, g2p=G2P_MODULE, voice=VOICE_MODULE, summary=None):
        self.write(os.path.join(self.models_dir, 'g2pModel.js'), G2P_MODULE)
        self.write(os.path.join(self.models_dir, 'voiceModel.js'), VOICE_MODULE)
        self.write(os.path.join(self.train_dir, 'g2pModel.js'), g2p)
        self.write(os.path.join(self.train_dir, 'g2p.done'), '')
        self.write(os.path.join(self.train_dir, 'voiceModel.js'), voice)
        self.write(os.path.join(self.train_dir, 'package.done'), '')
        self.write(os.path.join(self.train_dir, 'distill', 'summary.json'), json.dumps(summary or SUMMARY))

    def test_module_body(self):
        # Below the comment header - a line of weights below it starting with // isn't the header
        path = os.path.join(self.directory, 'module.js')
        self.write(path, '// Header\n\nexport const g2pModel = `\n//AAAA\n`;\n')
        self.assertEqual(trained.module_body(path), ['', 'export const g2pModel = `', '//AAAA', '`;', ''])
        self.write(path, '// Only a header')
        self.assertEqual(trained.module_body(path), [])

    def test_display_path(self):
        self.assertEqual(trained.display_path(os.path.join(ROOT, 'build', 'train')), os.path.join('build', 'train'))
        self.assertEqual(trained.display_path(self.directory), self.directory)

    def test_report(self):
        # The G2P identical below its header, the voice differing - its size and the gate's scores
        self.models(g2p=G2P_MODULE.replace('provenance A', 'provenance B'),
                    voice=VOICE_MODULE.replace('"commit":"a"', '"commit":"b"'))
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['report', self.train_dir]), 0)
        output = stdout.getvalue()
        self.assertIn(f'make train: the trained models in {self.train_dir} (lib/models/ unchanged)', output)
        self.assertIn('The voice - ', output)
        self.assertIn('voiceModel.js: differs from ', output)
        self.assertIn('    305,035 parameters, ', output)
        self.assertIn('    the listener panel: UTMOS 4.150 (shipped 4.147, +0.003), WER 1.10% (shipped 1.06%, +0.04), similarity 0.972\n',
                      output)
        self.assertIn('    the gate: passed (UTMOS at most 0.05 below', output)
        self.assertIn('g2pModel.js: identical to ', output)
        self.assertIn('(below its header)', output)
        self.assertIn('Next: the training dashboard', output)

        # The G2P differing - its gate's check line; the voice identical, its gate failed
        self.write(os.path.join(self.train_dir, 'logs', 'g2p.log'), 'check: the first\ncheck: the last\nanother line\n')
        self.models(g2p=G2P_MODULE.replace("'version': 1", "'version': 2"),
                    summary={**SUMMARY, 'rows': [SUMMARY['rows'][0], {**SUMMARY['rows'][1], 'withinTolerance': False}]})
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['report', self.train_dir]), 0)
        output = stdout.getvalue()
        self.assertIn('g2pModel.js: differs from ', output)
        self.assertIn('    check: the last\n', output)
        self.assertNotIn('check: the first', output)
        self.assertIn('voiceModel.js: identical to ', output)
        self.assertIn('    the gate: FAILED', output)

        # The G2P differing without its log; the voice without its parameter count, its scores, or the gate's student
        os.remove(os.path.join(self.train_dir, 'logs', 'g2p.log'))
        self.models(g2p=G2P_MODULE.replace("'version': 1", "'version': 2"), voice='export const weights = 1;\n',
                    summary={**SUMMARY, 'rows': SUMMARY['rows'][:1]})
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['report', self.train_dir]), 0)
        output = stdout.getvalue()
        self.assertNotIn('check:', output)
        self.assertNotIn('parameters', output)
        self.assertNotIn('listener panel', output)
        os.remove(os.path.join(self.train_dir, 'distill', 'summary.json'))
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['report', self.train_dir]), 0)
        self.assertNotIn('listener panel', stdout.getvalue())

    def test_report_one(self):
        # One model trained (make train-voice) - make train next, for both
        self.models()
        os.remove(os.path.join(self.train_dir, 'g2p.done'))
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['report', self.train_dir]), 0)
        self.assertIn('The voice - ', stdout.getvalue())
        self.assertNotIn('The G2P - ', stdout.getvalue())
        self.assertIn('Next: make train - make train-check and make train-install need both models\n', stdout.getvalue())

    def test_report_none(self):
        # No model has finished (a module without its stamp isn't trained)
        self.write(os.path.join(self.train_dir, 'voiceModel.js'), VOICE_MODULE)
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['report', self.train_dir]), 0)
        self.assertIn('  None - no model has finished its training\n', stdout.getvalue())
        self.assertNotIn('Next:', stdout.getvalue())

    def test_install(self):
        # The G2P identical below its header - kept; the voice differing - installed
        g2p_trained = G2P_MODULE.replace('provenance A', 'provenance B')
        voice_trained = VOICE_MODULE.replace('"commit":"a"', '"commit":"b"')
        self.models(g2p=g2p_trained, voice=voice_trained)
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['install', self.train_dir]), 0)
        output = stdout.getvalue()
        self.assertIn('is identical to', output)
        self.assertIn('(below its header) - ', output)
        self.assertIn('voiceModel.js is now ', output)
        self.assertNotIn('rebuilt', output)
        self.assertIn('install: next, make commit, then commit lib/models/\n', output)
        self.assertEqual(self.read(os.path.join(self.models_dir, 'g2pModel.js')), G2P_MODULE)
        self.assertEqual(self.read(os.path.join(self.models_dir, 'voiceModel.js')), voice_trained)

        # The G2P differing - installed, the voice's data rebuilt by the next make train; the voice identical - kept
        g2p_trained = G2P_MODULE.replace("'version': 1", "'version': 2")
        self.models(g2p=g2p_trained)
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['install', self.train_dir]), 0)
        output = stdout.getvalue()
        self.assertIn('g2pModel.js is now ', output)
        self.assertIn('voiceModel.js - ', output)
        self.assertIn('is rebuilt by the next make train', output)
        self.assertEqual(self.read(os.path.join(self.models_dir, 'g2pModel.js')), g2p_trained)

        # One model - the voice alone, then the G2P alone
        g2p_trained = G2P_MODULE.replace("'version': 1", "'version': 3")
        voice_trained = VOICE_MODULE.replace('"commit":"a"', '"commit":"c"')
        self.models(g2p=g2p_trained, voice=voice_trained)
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['install', self.train_dir, '--model', 'voice']), 0)
        self.assertIn('voiceModel.js is now ', stdout.getvalue())
        self.assertNotIn('g2pModel.js', stdout.getvalue())
        self.assertEqual(self.read(os.path.join(self.models_dir, 'voiceModel.js')), voice_trained)
        self.assertEqual(self.read(os.path.join(self.models_dir, 'g2pModel.js')), G2P_MODULE)
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['install', self.train_dir, '--model', 'g2p']), 0)
        self.assertIn('g2pModel.js is now ', stdout.getvalue())
        self.assertNotIn('voiceModel.js', stdout.getvalue())
        self.assertEqual(self.read(os.path.join(self.models_dir, 'g2pModel.js')), g2p_trained)

        # Both identical - nothing installed
        self.models(g2p=G2P_MODULE)
        with captured() as (stdout, _):
            self.assertEqual(trained.main(['install', self.train_dir]), 0)
        self.assertNotIn('is now', stdout.getvalue())
        self.assertNotIn('make commit', stdout.getvalue())

    def test_main(self):
        with unittest.mock.patch.object(sys, 'argv', ['trained', 'report', self.train_dir]), captured() as (stdout, _), \
                warnings.catch_warnings():
            warnings.filterwarnings('ignore', message='.*found in sys.modules', category=RuntimeWarning)
            with self.assertRaises(SystemExit) as context:
                runpy.run_module('picovox_train.trained', run_name='__main__')
        self.assertEqual(context.exception.code, 0)
        self.assertIn('None', stdout.getvalue())
