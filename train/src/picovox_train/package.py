"""
Packaging - an exported acoustic model (export.py's <voice>.json manifest and <voice>.bin weights) as a generated
JavaScript module, which lib/package.js loads the same way in Node, the browser, and a Web Worker (a plain import -
no fetch, no file system):

    PYTHONPATH=train/src build/venv-train/bin/python -B -m picovox_train.package build/train/eval/voice/multi -o build/multi.js

    import * as voice from './build/multi.js';
    import {loadPackagedModel} from './lib/package.js';
    const model = await loadPackagedModel(voice);     // lib/model.js's model, as loadModel(manifest, buffer) gives

The module (headed "Generated by package.py - do not edit") exports:

- manifest - the export's manifest, as a JavaScript object literal (compact JSON, long strings concatenated, wrapped
  between tokens at LINE_LENGTH characters)
- encoding - 'raw' (the weights are the .bin's bytes - deflate barely shrinks quantized weights, which look random, and
  base64's 33% mostly disappears under the HTTP compression static hosts apply to JavaScript)
- weights - the bytes as base64, in a template literal wrapped at LINE_LENGTH characters (the loader drops the line
  breaks)

The module's size - its bytes and gzip bytes - is printed (JSON).

Provenance (make train's package step): --provenance adds the manifest's "provenance" - the git commit (and whether
the tree had changes), the recipe's SHA-256 (--recipe, train/data/train.json), each training data directory's index
SHA-256 (--data DIR ...), and the gate's scores (--scores, the evaluation's result.json: UTMOS, WER, similarity).
"""

import argparse
import base64
import gzip
import hashlib
import json
import os
import subprocess
import sys

from . import ROOT, quant


# The longest generated line
LINE_LENGTH = 120

# The generated module's header
HEADER = '// Generated by picovox_train.package - do not edit'


# A value's JSON tokens - (text, whether a line may break after it); a string longer than STRING_CHUNK characters is
# split into a concatenation of string literals (so the value is a JavaScript literal, not JSON)
STRING_CHUNK = 60


def _tokens(value):
    if isinstance(value, dict):
        yield '{', True
        for index, (key, item) in enumerate(value.items()):
            if index:
                yield ',', True
            yield json.dumps(key, ensure_ascii=False), False
            yield ':', True
            yield from _tokens(item)
        yield '}', False
    elif isinstance(value, (list, tuple)):
        yield '[', True
        for index, item in enumerate(value):
            if index:
                yield ',', True
            yield from _tokens(item)
        yield ']', False
    elif isinstance(value, str) and len(value) > STRING_CHUNK:
        chunks = [value[ix:ix + STRING_CHUNK] for ix in range(0, len(value), STRING_CHUNK)]
        for index, chunk in enumerate(chunks):
            if index:
                yield ' + ', True
            yield json.dumps(chunk, ensure_ascii=False), False
    else:
        yield json.dumps(value, ensure_ascii=False), False


# A value as a compact JavaScript literal (JSON, long strings concatenated), wrapped between tokens at a line length
def wrap_json(value, width=LINE_LENGTH, indent='    ', first=0):
    lines = []
    line = ''
    breakable = ''
    for text, can_break in _tokens(value):
        limit = width - (len(indent) if lines else first)
        if len(line) + len(text) > limit and breakable:
            lines.append(breakable.rstrip())
            line = line[len(breakable):]
            breakable = ''
        line += text
        if can_break:
            breakable = line
    lines.append(line)
    return ('\n' + indent).join(lines)


# Base64 of bytes in lines of at most width characters
def wrap_base64(data, width=LINE_LENGTH):
    text = base64.b64encode(data).decode('ascii')
    return '\n'.join(text[ix:ix + width] for ix in range(0, len(text), width))


# The module's text for a manifest and weights (bytes)
def module_text(manifest, weights):
    voice = manifest.get('voice', 'model')
    return '\n'.join([
        HEADER,
        f'// The {voice} acoustic model ({manifest.get("parameterCount")} parameters, {quant.BITS}-bit weights) for',
        f'// lib/package.js loadPackagedModel - the export\'s manifest, and its weights ({len(weights)} bytes) as base64.',
        '',
        f'export const manifest = {wrap_json(manifest, first=len("export const manifest = "))};',
        '',
        "export const encoding = 'raw';",
        '',
        'export const weights = `',
        wrap_base64(weights),
        '`;',
        ''
    ])


# A file's SHA-256 (hex)
def file_sha256(path):
    with open(path, 'rb') as file:
        return hashlib.sha256(file.read()).hexdigest()


# The provenance of a packaged model - {commit, dirty, recipe, data, scores}
def provenance(recipe=None, data_dirs=(), scores=None):
    root = ROOT
    git = ['git', '-C', root]
    result = {'commit': subprocess.run(git + ['rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip(),
              'dirty': bool(subprocess.run(git + ['status', '--porcelain', '--untracked-files=no'], capture_output=True, text=True,
                                           check=True).stdout.strip())}
    if recipe:
        result['recipe'] = {'path': os.path.relpath(os.path.abspath(recipe), root), 'sha256': file_sha256(recipe)}
    if data_dirs:
        result['data'] = {os.path.basename(os.path.normpath(directory)): file_sha256(os.path.join(directory, 'index.json'))
                          for directory in data_dirs}
    if scores:
        with open(scores, encoding='utf-8') as file:
            panel = json.load(file)['panel']
        result['scores'] = {key: round(value, 4) for key, value in panel.items()}
    return result


# A module's text's size - {bytes, gzipBytes}
def module_size(text):
    encoded = text.encode('utf-8')
    return {'bytes': len(encoded), 'gzipBytes': len(gzip.compress(encoded, 9, mtime=0))}


# Package an export (its path without extension) - the module's text
def package(model_path, provenance_info=None):
    with open(f'{model_path}.json', encoding='utf-8') as file:
        manifest = json.load(file)
    if provenance_info:
        manifest['provenance'] = provenance_info
    with open(f'{model_path}.bin', 'rb') as file:
        weights = file.read()
    return module_text(manifest, weights)


def main(argv=None):
    parser = argparse.ArgumentParser(prog='python -m picovox_train.package',
                                     description='An exported model as a generated JavaScript module')
    parser.add_argument('model', help='the exported model (train/data/<voice>, without extension)')
    parser.add_argument('-o', '--output', required=True)
    parser.add_argument('--provenance', action='store_true', help='add the manifest\'s provenance (the commit and the below)')
    parser.add_argument('--recipe', help='the recipe (train/data/train.json) - its hash in the provenance')
    parser.add_argument('--data', nargs='*', default=[], help='training data directories - their index hashes')
    parser.add_argument('--scores', help='the evaluation\'s result.json - its panel scores')
    args = parser.parse_args(argv)
    info = provenance(args.recipe, args.data, args.scores) if args.provenance else None
    text = package(args.model, info)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, 'w', encoding='utf-8') as file:
        file.write(text)
    print(json.dumps({'output': args.output, **module_size(text)}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
